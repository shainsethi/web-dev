let cart = ["milk", "bread"];

console.log("push returns:", cart.push("eggs"));
console.log("After push:", cart);

console.log("pop returns:", cart.pop());
console.log("After pop:", cart);

console.log("unshift returns:", cart.unshift("tea"));
console.log("After unshift:", cart);

console.log("shift returns:", cart.shift());
console.log("After shift:", cart);
