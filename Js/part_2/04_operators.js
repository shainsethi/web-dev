let count = 5;

console.log("Post-increment returns:", count++);
console.log("Value after post-increment:", count);
console.log("Pre-increment returns:", ++count);
console.log("Post-decrement returns:", count--);
console.log("Pre-decrement returns:", --count);

let score = 10;

score += 5;
console.log("After += 5:", score);
score -= 3;
console.log("After -= 3:", score);
score *= 2;
console.log("After *= 2:", score);
score /= 4;
console.log("After /= 4:", score);
score %= 4;
console.log("After %= 4:", score);
score **= 3;
console.log("After **= 3:", score);
